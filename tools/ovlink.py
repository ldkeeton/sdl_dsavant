#!/usr/bin/env python3
"""Make one overlay a single object with its own namespace (tools/build.py).

On DOS each overlay was linked on its own against DS's symbols, so overlays
could define the same names.  Here they are all linked into DS, so:

  * ld -r combines the overlay's objects (and the shared members it took)
    into NAME.o
  * every global symbol NAME.o defines is made local, except ovmain, which
    becomes ovmain_NAME; what it leaves undefined still resolves to DS
  * its writable data goes into sections of its own, so the loader can save
    it at startup and put it back each time the overlay is loaded (an
    overlay starts with fresh data, as when DOS read it from disk):
      ELF: ovd_NAME (.data) and ovb_NAME (.bss), bounded by __start_/__stop_
      PE:  .data$ovNAME$m, between markers in .data$ovNAME$a and $z (bss
           goes there too, as zeroed data)
"""

import os
import subprocess
import sys


def run(argv):
    r = subprocess.run(argv, capture_output=True, text=True)
    if r.returncode:
        sys.exit('ovlink: %s failed:\n%s' % (argv[0], r.stderr))
    return r.stdout


def sections(t, obj):
    out = run([t.objdump if hasattr(t, 'objdump') else 'objdump', '-h', obj])
    names = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 7 and parts[0].isdigit():
            names.append(parts[1])
    return names


def make(t, name, objs, out):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    combined = out + '.r.o'
    run([t.ld, '-r', '-o', combined] + objs)
    nm = run([t.nm, '-P', combined])
    defined = []
    for line in nm.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[1].isupper() and parts[1] not in 'UNW':
            if t.name == 'win' and parts[0].startswith('.'):
                continue
            defined.append(parts[0])
    entry = 'ovmain'
    if entry not in defined:
        sys.exit('ovlink: %s defines no %s' % (name, entry))
    argv = [t.objcopy]
    for sym in defined:
        if sym != entry:
            argv += ['--localize-symbol', sym]
    argv += ['--redefine-sym', '%s=%s_%s' % (entry, entry, name)]
    for sec in sections(t, combined):
        if t.name == 'linux':
            if sec == '.data' or sec.startswith('.data.'):
                argv += ['--rename-section', '%s=ovd_%s' % (sec, name)]
            elif sec == '.bss' or sec.startswith('.bss.'):
                argv += ['--rename-section', '%s=ovb_%s' % (sec, name)]
        else:
            if sec == '.data' or sec == '.bss':
                argv += ['--rename-section', '%s=.data$ov%s$m' % (sec, name)]
                if sec == '.bss':
                    argv[-1] += ',alloc,load,contents,data'
    argv += [combined, out]
    run(argv)
    os.remove(combined)


def table_source(t, names):
    """C for the table of overlays: name, entry, data bounds."""
    lines = ['/* generated by tools/ovlink.py */', '#include "overlay.h"', '']
    for n in names:
        lines.append('extern short ovmain_%s(void);' % n)
        if t.name == 'linux':
            for p in ('__start_ovd_', '__stop_ovd_', '__start_ovb_', '__stop_ovb_'):
                lines.append('extern char %s%s[] __attribute__((weak));' % (p, n))
        else:
            lines.append('__attribute__((section(".data$ov%s$a"), aligned(16))) char ov_%s_a[16];' % (n, n))
            lines.append('__attribute__((section(".data$ov%s$z"))) char ov_%s_z[1];' % (n, n))
    lines += ['', 'const struct overlay_entry overlay_table[] = {']
    for n in names:
        if t.name == 'linux':
            lines.append('    {"%s", ovmain_%s, __start_ovd_%s, __stop_ovd_%s, __start_ovb_%s, __stop_ovb_%s},'
                         % ((n,) * 6))
        else:
            lines.append('    {"%s", ovmain_%s, ov_%s_a + 16, ov_%s_z, 0, 0},' % ((n,) * 4))
    lines += ['    {0}', '};', '']
    return '\n'.join(lines)
